import { Hono } from "hono";
import { z } from "zod";
import type { AppEnv } from "../../lib/types";
import { ok, okList, parse } from "../../lib/http";
import { forbidden, unauthorized } from "../../lib/errors";
import * as svc from "./service";
export const superAdminRoutes = new Hono<AppEnv>();
superAdminRoutes.use("*", async (c, next) => { const user = c.get("user"); if (!user) throw unauthorized(); if (!user.isPlatformAdmin) throw forbidden("Platform admin access required"); await next(); });
const body = z.record(z.string(), z.unknown());
superAdminRoutes.get("/organisations", async (c) => okList(c, await svc.listOrganisations(c.get("db")), 0, 1, 1000));
superAdminRoutes.post("/organisations", async (c) => ok(c, await svc.saveOrganisation(c.get("db"), undefined, parse(body, await c.req.json()) as any), 201));
superAdminRoutes.put("/organisations/:id", async (c) => ok(c, await svc.saveOrganisation(c.get("db"), c.req.param("id"), parse(body, await c.req.json()) as any)));
superAdminRoutes.get("/organisations/:id/features", async (c) => ok(c, await svc.listFlags(c.get("db"), c.req.param("id"))));
superAdminRoutes.put("/organisations/:id/features/:flag", async (c) => ok(c, await svc.saveFlag(c.get("db"), c.req.param("id"), c.req.param("flag"), parse(z.object({ enabled: z.boolean() }), await c.req.json()).enabled)));
superAdminRoutes.get("/stats", async (c) => ok(c, await svc.stats(c.get("db"))));
